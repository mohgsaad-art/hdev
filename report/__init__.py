# STATUS: NEW (PR 8, Bob to review). the Step 8 report-export package.
#
# this top-level package turns the demo results JSON + the audit source table + the OPEN fields with
# values into a client-facing report in two formats: a PDF (reportlab) and an Excel workbook (openpyxl).
# both carry the §5.6 nine sections in the SAME order (report/builder.py is the single source of truth)
# and, in demo/illustrative mode, the "Illustrative values - sample case" watermark on every page/sheet.
#
# the public surface is two PURE functions returning bytes:
#   build_pdf(results, audit, scenarios=None, open_fields=None, *, illustrative) -> bytes
#   build_xlsx(results, audit, scenarios=None, open_fields=None, *, illustrative) -> bytes
# each assembles the sections via builder.assemble_sections and renders them with the format renderer,
# then runs the §8 guard (assert_no_hidden_fields) over the generated bytes defensively so a report can
# never leak a collapsed/hidden field name even if a caller mis-wires the inputs.
#
# §0: all logic lives in Python; the browser only triggers the download. no network, no AI provider.
from typing import Any, Mapping, Optional, Sequence

from .builder import (
    NOT_AVAILABLE,
    SECTION_TITLES,
    WATERMARK_TEXT,
    assemble_sections,
    assert_no_hidden_fields,
    hidden_field_names,
    sections_text,
)
from .pdf import build_pdf as _render_pdf
from .xlsx import build_xlsx as _render_xlsx

__all__ = [
    "build_pdf",
    "build_xlsx",
    "assemble_sections",
    "assert_no_hidden_fields",
    "hidden_field_names",
    "sections_text",
    "SECTION_TITLES",
    "WATERMARK_TEXT",
    "NOT_AVAILABLE",
]


def build_pdf(
    results: Mapping[str, Any],
    audit: Mapping[str, Any],
    scenarios: Optional[Mapping[str, Any]] = None,
    open_fields: Optional[Sequence[Mapping[str, Any]]] = None,
    *,
    illustrative: bool,
) -> bytes:
    # assemble the 9 sections, run the §8 guard over the CONTENT, then render to PDF bytes. the guard
    # runs on the assembled sections (the client-visible words) rather than the binary PDF container so
    # it can never false-positive on PDF structural tokens (e.g. the '/Length' dictionary key).
    sections = assemble_sections(results, audit, scenarios, open_fields, illustrative=illustrative)
    assert_no_hidden_fields(sections)
    return _render_pdf(sections, illustrative=illustrative)


def build_xlsx(
    results: Mapping[str, Any],
    audit: Mapping[str, Any],
    scenarios: Optional[Mapping[str, Any]] = None,
    open_fields: Optional[Sequence[Mapping[str, Any]]] = None,
    *,
    illustrative: bool,
) -> bytes:
    # assemble the 9 sections, run the §8 guard over the CONTENT, then render to .xlsx bytes.
    sections = assemble_sections(results, audit, scenarios, open_fields, illustrative=illustrative)
    assert_no_hidden_fields(sections)
    return _render_xlsx(sections, illustrative=illustrative)
