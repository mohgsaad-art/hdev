# STATUS: NEW (PR 8, Bob to review). the SHARED report section-assembly logic (Step 8).
#
# this is the single source of truth for the §5.6 report. assemble_sections() turns the inputs (demo
# results JSON + the audit source table + saved scenarios + the OPEN fields with values) into an
# ORDERED list of section dicts that BOTH renderers (report/pdf.py and report/xlsx.py) consume, so the
# PDF and the Excel can never drift. §0: all logic lives here in Python; every number is READ from the
# results JSON / audit data - this module invents nothing. when a results field is null/absent, the
# cell reads the literal "Not yet available" (NOT_AVAILABLE) so real mode degrades without a fake number.
#
# the 9 sections, IN THIS EXACT ORDER (both formats must contain all 9, each named):
#   1 Summary, 2 Your fleet & inputs, 3 Energy, 4 Charging, 5 Grid & flexibility,
#   6 Total cost, 7 CO2, 8 Plan, 9 Inputs & sources.
#
# §8 method-hiding (the hard line, enforced in section 9 and by assert_no_hidden_fields):
#   section 9 "Inputs & sources" lists SOURCE TYPES + COUNTS from the audit table (counts only, never a
#   field name) and the OPEN fields with their value + source. OPEN fields are the ONLY fields that may
#   be NAMED anywhere in the report. a collapsed/hidden field id/label/value NEVER appears; collapsed
#   fields contribute to the counts only. assert_no_hidden_fields(text) is the programmatic guard that
#   proves this on the generated bytes (mirrors audit/sources.py rows_contain_no_field_names).
#
# illustrative watermark: the sample case is illustrative, so the renderers stamp the EXACT text
# WATERMARK_TEXT = "Illustrative values - sample case" on every PDF page / every Excel sheet whenever
# illustrative=True. the watermark string lives here so both formats use the identical text.
#
# purity: assemble_sections is a pure function of its arguments. no network, no AI provider, no file IO.
from typing import Any, Dict, List, Mapping, Optional, Sequence

# the literal shown for any value that is null/absent (real-mode degradation; never invent a number).
NOT_AVAILABLE = "Not yet available"

# the EXACT illustrative watermark text, used on every PDF page and every Excel sheet (demo only).
# note: a plain ASCII hyphen is used (not an en dash) so the string round-trips through PDF text
# extraction and the §8/byte checks without unicode surprises.
WATERMARK_TEXT = "Illustrative values - sample case"

# the 9 section titles IN ORDER. the tuple is the single source of truth for titles + ordering.
SECTION_TITLES: Sequence[str] = (
    "1 Summary",
    "2 Your fleet & inputs",
    "3 Energy",
    "4 Charging",
    "5 Grid & flexibility",
    "6 Total cost",
    "7 CO\u2082",
    "8 Plan",
    "9 Inputs & sources",
)

# the three client-facing charging-approach labels (§8). never an internal lever key.
_PRIORITY_LABEL = {
    "lowest_cost": "Lowest cost",
    "grid_friendly": "Grid-friendly",
    "ready_earliest": "Ready earliest",
}
_PRICE_LABEL = {"low": "Low", "expected": "Expected", "high": "High"}
_WEATHER_LABEL = {"normal": "Normal year", "cold_winter": "Cold winter"}

# the 12 month labels for the energy section's monthly series (plain words, no field name).
_MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


# ---------------------------------------------------------------------------
# small value helpers. every one degrades a null/absent value to NOT_AVAILABLE.
# ---------------------------------------------------------------------------
def _present(value: Any) -> bool:
    return value is not None


def _text(value: Any) -> str:
    # a plain string for a label/verdict value; NOT_AVAILABLE when absent.
    if not _present(value):
        return NOT_AVAILABLE
    return str(value)


def _num(value: Any, *, digits: int = 0, suffix: str = "") -> str:
    # a human number string with thousands separators; NOT_AVAILABLE when absent. integers drop the
    # decimal; floats are rounded to `digits`. never invents a value.
    if not _present(value):
        return NOT_AVAILABLE
    try:
        number = float(value)
    except (TypeError, ValueError):
        return _text(value)
    if digits <= 0:
        body = f"{round(number):,}"
    else:
        body = f"{number:,.{digits}f}"
    return f"{body}{suffix}"


def _priority_label(value: Any) -> str:
    return _PRIORITY_LABEL.get(value, _text(value))


def _price_label(value: Any) -> str:
    return _PRICE_LABEL.get(value, _text(value))


def _weather_label(value: Any) -> str:
    return _WEATHER_LABEL.get(value, _text(value))


def _row(label: str, value: Any) -> Dict[str, str]:
    # one key/value row for a section. the value is already a formatted string.
    return {"label": label, "value": value if isinstance(value, str) else _text(value)}


def _get(mapping: Any, *keys: str) -> Any:
    # safe nested lookup through dict-like structures; returns None at the first missing/non-mapping.
    cur = mapping
    for key in keys:
        if not isinstance(cur, Mapping):
            return None
        cur = cur.get(key)
    return cur


# ---------------------------------------------------------------------------
# the 9 section builders. each returns {"title", "rows"} where rows is a list of
# {"label","value"} dicts (both renderers lay these out as a simple two-column table).
# ---------------------------------------------------------------------------
def _section_summary(results: Mapping[str, Any]) -> Dict[str, Any]:
    verdict = _get(results, "verdict") or {}
    kpis = _get(results, "kpis") or {}
    rows = [
        _row("Verdict", _text(verdict.get("headline"))),
        _row("Why", _text(verdict.get("reason"))),
        _row("Battery per truck (kWh)", _num(kpis.get("battery_kwh"))),
        _row(
            "Chargers",
            NOT_AVAILABLE
            if not _present(kpis.get("charger_count")) and not _present(kpis.get("charger_kw"))
            else f"{_num(kpis.get('charger_count'))} x {_num(kpis.get('charger_kw'))} kW",
        ),
        _row(
            "Busiest-day power vs site limit (kW)",
            NOT_AVAILABLE
            if not _present(kpis.get("grid_peak_kw")) and not _present(kpis.get("grid_limit_kw"))
            else f"{_num(kpis.get('grid_peak_kw'))} of {_num(kpis.get('grid_limit_kw'))}",
        ),
        _row("Cost difference over the years kept (DKK)", _num(kpis.get("tco_diff_dkk"))),
        _row("Break-even year", _num(kpis.get("break_even_year"))),
        _row("CO\u2082 saved (t/year)", _num(kpis.get("co2_saved_t_per_year"), digits=1)),
        _row("Every truck ready by", _text(kpis.get("ready_by"))),
    ]
    return {"title": SECTION_TITLES[0], "rows": rows}


def _section_fleet_inputs(results: Mapping[str, Any]) -> Dict[str, Any]:
    settings = _get(results, "settings") or {}
    summary = _get(results, "inputs_summary") or {}
    rows = [
        _row("Trucks", _num(settings.get("fleet_size"))),
        _row("Charging approach", _priority_label(settings.get("charging_priority"))),
        _row("Electricity price", _price_label(settings.get("electricity_price"))),
        _row("Weather", _weather_label(settings.get("weather_year"))),
        _row("Years kept", _num(settings.get("ownership_years"))),
        _row("Shift end", _text(settings.get("shift_end"))),
        _row("Working days a year", _num(results.get("working_days"))),
        _row("Truck-days simulated", _num(results.get("truck_days_simulated"))),
        _row("Inputs from your data", _num(summary.get("from_data"))),
        _row("Inputs using standard values", _num(summary.get("standard"))),
        _row("Inputs still missing", _num(summary.get("missing"))),
        _row("Inputs in total", _num(summary.get("total"))),
    ]
    return {"title": SECTION_TITLES[1], "rows": rows}


def _section_energy(results: Mapping[str, Any]) -> Dict[str, Any]:
    energy = _get(results, "energy") or {}
    rows = [
        _row("Average day (kWh)", _num(energy.get("avg_day_kwh"), digits=1)),
        _row("Hardest day (kWh)", _num(energy.get("hardest_day_kwh"), digits=1)),
    ]
    monthly = energy.get("monthly_avg_kwh")
    if isinstance(monthly, Sequence) and not isinstance(monthly, (str, bytes)):
        for i, label in enumerate(_MONTHS):
            value = monthly[i] if i < len(monthly) else None
            rows.append(_row(f"{label} average (kWh)", _num(value, digits=1)))
    else:
        rows.append(_row("Monthly averages (kWh)", NOT_AVAILABLE))
    return {"title": SECTION_TITLES[2], "rows": rows}


def _section_charging(results: Mapping[str, Any]) -> Dict[str, Any]:
    strategies = _get(results, "charging", "strategies")
    rows: List[Dict[str, str]] = []
    if isinstance(strategies, Sequence) and not isinstance(strategies, (str, bytes)) and strategies:
        for strategy in strategies:
            if not isinstance(strategy, Mapping):
                continue
            name = _priority_label(strategy.get("priority"))
            fits = strategy.get("fits_grid")
            fits_text = NOT_AVAILABLE if fits is None else ("fits the site" if fits else "over the site limit")
            detail = (
                f"{_num(strategy.get('charger_kw'))} kW chargers, "
                f"busiest-day {_num(strategy.get('peak_kw'))} kW, "
                f"{_num(strategy.get('cost_per_year_dkk'))} DKK/year, "
                f"{fits_text}, ready by {_text(strategy.get('ready_by'))}"
            )
            rows.append(_row(name, detail))
    else:
        rows.append(_row("Charging approaches", NOT_AVAILABLE))
    return {"title": SECTION_TITLES[3], "rows": rows}


def _section_grid(results: Mapping[str, Any]) -> Dict[str, Any]:
    grid = _get(results, "grid") or {}
    rows = [
        _row("Site power limit (kW)", _num(grid.get("limit_kw"))),
        _row("Spare power to share each day (MWh)", _num(grid.get("flex_mwh_per_day"), digits=3)),
    ]
    load = grid.get("load_24h_kw")
    flex = grid.get("flex_24h_kw")
    if isinstance(load, Sequence) and not isinstance(load, (str, bytes)):
        for hour in range(24):
            value = load[hour] if hour < len(load) else None
            rows.append(_row(f"Depot load at {hour:02d}:00 (kW)", _num(value, digits=1)))
    else:
        rows.append(_row("Depot load across the day (kW)", NOT_AVAILABLE))
    if isinstance(flex, Sequence) and not isinstance(flex, (str, bytes)):
        for hour in range(24):
            value = flex[hour] if hour < len(flex) else None
            rows.append(_row(f"Spare power at {hour:02d}:00 (kW)", _num(value, digits=1)))
    else:
        rows.append(_row("Spare power across the day (kW)", NOT_AVAILABLE))
    return {"title": SECTION_TITLES[4], "rows": rows}


def _section_total_cost(results: Mapping[str, Any]) -> Dict[str, Any]:
    tco = _get(results, "tco") or {}
    categories = tco.get("categories")
    rows: List[Dict[str, str]] = []
    if isinstance(categories, Sequence) and not isinstance(categories, (str, bytes)) and categories:
        for category in categories:
            if not isinstance(category, Mapping):
                continue
            rows.append(
                _row(
                    _text(category.get("name")),
                    f"diesel {_num(category.get('diesel'))} DKK vs electric {_num(category.get('electric'))} DKK",
                )
            )
    else:
        rows.append(_row("Cost categories", NOT_AVAILABLE))
    rows.append(_row("Break-even year", _num(tco.get("break_even_year"))))
    return {"title": SECTION_TITLES[5], "rows": rows}


def _section_co2(results: Mapping[str, Any]) -> Dict[str, Any]:
    co2 = _get(results, "co2") or {}
    rows = [
        _row("Diesel (t/year)", _num(co2.get("diesel_t_per_year"), digits=1)),
        _row("Electric (t/year)", _num(co2.get("electric_t_per_year"), digits=1)),
    ]
    cumulative = co2.get("cumulative_saved_t")
    if isinstance(cumulative, Sequence) and not isinstance(cumulative, (str, bytes)) and cumulative:
        last = cumulative[-1]
        rows.append(_row(f"Saved over {len(cumulative) - 1} years (t)", _num(last, digits=1)))
    else:
        rows.append(_row("Saved over the years kept (t)", NOT_AVAILABLE))
    return {"title": SECTION_TITLES[6], "rows": rows}


def _section_plan(results: Mapping[str, Any]) -> Dict[str, Any]:
    plan = _get(results, "plan")
    rows: List[Dict[str, str]] = []
    if isinstance(plan, Sequence) and not isinstance(plan, (str, bytes)) and plan:
        for step in plan:
            if not isinstance(step, Mapping):
                continue
            rows.append(_row(_text(step.get("when")), _text(step.get("text"))))
    else:
        rows.append(_row("Plan", NOT_AVAILABLE))
    return {"title": SECTION_TITLES[7], "rows": rows}


def _section_inputs_sources(
    audit: Mapping[str, Any],
    open_fields: Sequence[Mapping[str, Any]],
) -> Dict[str, Any]:
    # THE §8-CRITICAL SURFACE. two blocks:
    #   (a) the SOURCE TYPES + COUNTS from the audit table (counts only; never a field name) + total.
    #   (b) the OPEN fields with their value + source (open fields are the ONLY fields that may be named).
    rows: List[Dict[str, str]] = []

    rows.append(_row("Where every input came from", ""))
    table = audit if isinstance(audit, Mapping) else {}
    source_rows = table.get("rows") if isinstance(table.get("rows"), Sequence) else []
    for source in source_rows:
        if not isinstance(source, Mapping):
            continue
        status = source.get("status")
        value = _num(source.get("count"))
        if status:
            value = f"{value} ({status})"
        rows.append(_row(_text(source.get("source_type")), value))
    rows.append(_row("Inputs in total", _num(table.get("total"))))

    # (b) the open fields with values. these are the only named fields in the whole report.
    rows.append(_row("Open inputs you can see and change", ""))
    any_open = False
    for field in open_fields or []:
        if not isinstance(field, Mapping):
            continue
        any_open = True
        unit = field.get("unit")
        value = field.get("value")
        value_text = NOT_AVAILABLE if not _present(value) else str(value)
        if _present(value) and unit:
            value_text = f"{value_text} {unit}"
        source = field.get("source")
        if source:
            value_text = f"{value_text} - {source}"
        rows.append(_row(_text(field.get("label")), value_text))
    if not any_open:
        rows.append(_row("Open inputs", NOT_AVAILABLE))

    return {"title": SECTION_TITLES[8], "rows": rows}


# ---------------------------------------------------------------------------
# the public assembler both renderers consume.
# ---------------------------------------------------------------------------
def assemble_sections(
    results: Mapping[str, Any],
    audit: Mapping[str, Any],
    scenarios: Optional[Mapping[str, Any]] = None,
    open_fields: Optional[Sequence[Mapping[str, Any]]] = None,
    *,
    illustrative: bool,
) -> List[Dict[str, Any]]:
    # pure function. returns the ORDERED list of 9 section dicts {title, rows}. `scenarios` is accepted
    # for forward-compatibility (the saved-scenario list) but the §5.6 report body is driven by the
    # single run's results; it is not required for any of the 9 sections. every number is read from the
    # inputs; a null/absent value becomes NOT_AVAILABLE.
    results = results if isinstance(results, Mapping) else {}
    audit = audit if isinstance(audit, Mapping) else {}
    open_fields = list(open_fields or [])

    sections = [
        _section_summary(results),
        _section_fleet_inputs(results),
        _section_energy(results),
        _section_charging(results),
        _section_grid(results),
        _section_total_cost(results),
        _section_co2(results),
        _section_plan(results),
        _section_inputs_sources(audit, open_fields),
    ]
    # the order is fixed by SECTION_TITLES; assert it so the two renderers can never drift.
    assert [s["title"] for s in sections] == list(SECTION_TITLES), "report section order drifted"
    return sections


# ---------------------------------------------------------------------------
# the §8 programmatic guard, mirroring audit/sources.py rows_contain_no_field_names.
# ---------------------------------------------------------------------------
def hidden_field_names() -> List[str]:
    # every collapsed/hidden registry field id AND label - the names that must NEVER appear in a report.
    # open fields are excluded because they are the only fields the report is allowed to name.
    from src.registry import FIELDS

    names: List[str] = []
    for field in FIELDS:
        if getattr(field, "visibility", None) == "open":
            continue
        if field.id:
            names.append(field.id)
        label = getattr(field, "label", None)
        if label:
            names.append(label)
    return names


def sections_text(sections: Sequence[Mapping[str, Any]]) -> str:
    # flatten the assembled sections to the plain CONTENT text (titles + every label + every value).
    # this is the meaningful §8 surface - the words a client reads - independent of the binary PDF/xlsx
    # container (so the guard never false-positives on PDF syntax like the '/Length' dictionary key).
    parts: List[str] = []
    for section in sections or []:
        if not isinstance(section, Mapping):
            continue
        parts.append(str(section.get("title", "")))
        for row in section.get("rows") or []:
            if not isinstance(row, Mapping):
                continue
            parts.append(str(row.get("label", "")))
            parts.append(str(row.get("value", "")))
    return "\n".join(parts)


def assert_no_hidden_fields(data: Any) -> bool:
    # §8 GUARD. given the report CONTENT - either the assembled sections (preferred), a plain text
    # string, or raw bytes - assert that NO collapsed/hidden registry field id OR label appears
    # anywhere in it. returns True when the report is clean; raises AssertionError naming the offending
    # field otherwise. used defensively by the renderers and directly by the tests on both formats.
    #
    # note: when passed raw bytes we decode and scan them, but the PREFERRED input is the assembled
    # sections (or their plain text via sections_text), because a binary PDF/xlsx container embeds
    # structural tokens (e.g. the PDF '/Length' key) that are NOT client-visible content and would
    # otherwise cause a false positive. the renderers pass the sections; the tests additionally scan
    # the real rendered content (xlsx cells / introspected rows).
    if isinstance(data, (bytes, bytearray)):
        text = bytes(data).decode("latin-1", errors="ignore")
    elif isinstance(data, str):
        text = data
    elif isinstance(data, Sequence):
        # a sequence of assembled section dicts.
        text = sections_text(data)  # type: ignore[arg-type]
    else:
        text = str(data)

    for name in hidden_field_names():
        if name and name in text:
            raise AssertionError(f"\u00a78 violation: hidden/collapsed field name appeared in report: {name!r}")
    return True
